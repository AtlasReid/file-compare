const views = new WeakMap();
let sequence = 0;

export function renderMatrixText(element, value, doc) {
  const text = String(value);
  let view = views.get(element);
  if (view?.text === text) return view;
  const svgElement = (name, attrs = {}) => {
    const node = doc.createElementNS(NS, name);
    for (const [key, value] of Object.entries(attrs)) node.setAttribute(key, String(value));
    return node;
  };
  if (!view) {
    const accessible = doc.createElement('span'); accessible.className = 'sr-only';
    const svg = svgElement('svg', { 'aria-hidden': 'true', focusable: 'false', preserveAspectRatio: 'xMinYMid meet', class: 'matrix-glyphs' });
    const defs = svgElement('defs'), line = svgElement('g');
    svg.append(defs, line); element.replaceChildren(accessible, svg);
    view = { text: null, accessible, svg, defs, line, symbols: new Map(), prefix: `matrix-${++sequence}` };
    views.set(element, view);
  }
  view.text = text; view.accessible.textContent = text;
  const characters = [...text], width = Math.max(1, characters.length * 6 - 1);
  view.svg.setAttribute('viewBox', `0 -1 ${width} 10`);
  view.svg.style.setProperty('width', `${width / 10}em`);
  const positions = [];
  for (const [index, character] of characters.entries()) {
    const glyph = glyphs[character] ? character : '?';
    if (!view.symbols.has(glyph)) {
      const id = `${view.prefix}-${glyph.codePointAt(0)}`;
      const symbol = svgElement('g', { id });
      glyphs[glyph].forEach((row, y) => [...row].forEach((on, x) => {
        if (on === '1') symbol.append(svgElement('circle', { cx: x + .5, cy: y + .5, r: .36 }));
      }));
      view.defs.append(symbol); view.symbols.set(glyph, id);
    }
    positions.push(svgElement('use', { href: `#${view.symbols.get(glyph)}`, x: index * 6 }));
  }
  view.line.replaceChildren(...positions);
  return view;
}
